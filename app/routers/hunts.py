from fastapi import APIRouter, Depends, HTTPException, Query, Response, status
from sqlalchemy import select
from sqlalchemy.orm import Session

from .. import models, schemas
from ..deps import get_by_id, get_db, is_possible_id

router = APIRouter(prefix="/hunts", tags=["Hunt log"])


def _get_hunt(db: Session, hunt_id: int) -> models.HuntLog:
    hunt = get_by_id(db, models.HuntLog, hunt_id)
    if hunt is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Hunt log not found")
    return hunt


@router.get("/", response_model=list[schemas.HuntOut])
def list_hunts(
    criminal_id: int | None = Query(default=None, description="Only logs of this criminal"),
    db: Session = Depends(get_db),
):
    """List hunt logs (ordered by id). An unknown criminal_id simply gives an empty list."""
    if criminal_id is not None and not is_possible_id(criminal_id):
        return []
    stmt = select(models.HuntLog)
    if criminal_id is not None:
        stmt = stmt.where(models.HuntLog.criminal_id == criminal_id)
    return db.scalars(stmt.order_by(models.HuntLog.id)).all()


@router.get(
    "/{hunt_id}/",
    response_model=schemas.HuntOut,
    responses={404: {"description": "Hunt log not found"}},
)
def get_hunt(hunt_id: int, db: Session = Depends(get_db)):
    return _get_hunt(db, hunt_id)


@router.post(
    "/",
    response_model=schemas.HuntOut,
    status_code=status.HTTP_201_CREATED,
    responses={422: {"description": "Invalid body or criminal_id does not refer to an existing criminal"}},
)
def create_hunt(payload: schemas.HuntCreate, db: Session = Depends(get_db)):
    """Record a capture attempt. `created_at` is generated by the server."""
    if get_by_id(db, models.WantedCriminal, payload.criminal_id) is None:
        raise HTTPException(
            status.HTTP_422_UNPROCESSABLE_ENTITY,
            f"criminal_id {payload.criminal_id} does not refer to an existing criminal",
        )
    hunt = models.HuntLog(criminal_id=payload.criminal_id, success=payload.success, notes=payload.notes)
    db.add(hunt)
    db.commit()
    return hunt


@router.patch(
    "/{hunt_id}/",
    response_model=schemas.HuntOut,
    responses={404: {"description": "Hunt log not found"}, 422: {"description": "Invalid body"}},
)
def update_hunt(hunt_id: int, payload: schemas.HuntUpdate, db: Session = Depends(get_db)):
    """Update `success` and/or `notes`. Only the fields that are sent are changed."""
    hunt = _get_hunt(db, hunt_id)
    data = payload.model_dump(exclude_unset=True)
    if not data:
        raise HTTPException(status.HTTP_422_UNPROCESSABLE_ENTITY, "Provide at least one field to update: success, notes")
    if any(value is None for value in data.values()):
        raise HTTPException(status.HTTP_422_UNPROCESSABLE_ENTITY, "success and notes cannot be null")
    for key, value in data.items():
        setattr(hunt, key, value)
    db.commit()
    return hunt


@router.delete(
    "/{hunt_id}/",
    status_code=status.HTTP_204_NO_CONTENT,
    responses={404: {"description": "Hunt log not found"}},
)
def delete_hunt(hunt_id: int, db: Session = Depends(get_db)):
    hunt = _get_hunt(db, hunt_id)
    db.delete(hunt)
    db.commit()
    return Response(status_code=status.HTTP_204_NO_CONTENT)
